const STORAGE_KEY = 'masrafji-lang';
const LEGACY_STORAGE_KEY = 'masrafhi-lang';

function readInitialLang() {
  if (typeof window === 'undefined') return 'en';
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved === 'en' || saved === 'ar') return saved;
    const legacy = window.localStorage.getItem(LEGACY_STORAGE_KEY);
    if (legacy === 'en' || legacy === 'ar') {
      window.localStorage.setItem(STORAGE_KEY, legacy);
      window.localStorage.removeItem(LEGACY_STORAGE_KEY);
      return legacy;
    }
  } catch {
    /* ignore */
  }
  if (typeof navigator !== 'undefined' && navigator.language?.startsWith('ar')) return 'ar';
  return 'en';
}

const LangContext = createContext({
  lang: 'en',
  dir: 'ltr',
  setLang: () => {},
  t: (k) => k,
});

export function LangProvider({ children }) {
  const [lang, setLang] = useState(readInitialLang);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    try {
      window.localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      /* ignore */
    }
  }, [lang]);

  const value = useMemo(() => {
    const t = (key, vars) => {
      if (!key) return '';
      const segments = key.split('.');
      let cursor = dict[lang];
      for (const seg of segments) {
        if (cursor && typeof cursor === 'object' && seg in cursor) {
          cursor = cursor[seg];
        } else {
          // Fallback to English if missing in selected language
          let fallback = dict.en;
          for (const s of segments) {
            if (fallback && typeof fallback === 'object' && s in fallback) {
              fallback = fallback[s];
            } else {
              return key;
            }
          }
          cursor = fallback;
          break;
        }
      }
      if (typeof cursor !== 'string') return key;
      if (vars) {
        return Object.entries(vars).reduce(
          (s, [k, v]) => s.replaceAll(`{${k}}`, String(v)),
          cursor,
        );
      }
      return cursor;
    };
    return {
      lang,
      dir: lang === 'ar' ? 'rtl' : 'ltr',
      setLang,
      t,
    };
  }, [lang]);

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang() {
  return useContext(LangContext);
}

export function useT() {
  return useContext(LangContext).t;
}

/**
 * Translate a category label key (the English category name) for display.
 */
export function useCategoryLabel() {
  const { t } = useContext(LangContext);
  return (key) => {
    const v = t(`categories.${key}`);
    return v === `categories.${key}` ? key : v;
  };
}

/**
 * Translate a month abbreviation. Used for chart x-axis ticks.
 */
export function useMonthLabel() {
  const { t } = useContext(LangContext);
  return (key) => {
    const v = t(`months.${key}`);
    return v === `months.${key}` ? key : v;
  };
}
